"""Build the marketplace catalog from the metadata owned by each plugin."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[2]
if not __package__:
    sys.path.insert(0, str(ROOT))

from tooling.scripts.studio_requirements import studio_requirements  # noqa: E402
from tooling.scripts.operation_metadata import validate_snapshot  # noqa: E402


def render_registry(root: Path = ROOT, *, ref: str | None = None, release: bool = False) -> dict:
    repository = tomllib.loads((root / "tooling/catalog.toml").read_text(encoding="utf-8"))["repository"]
    source_ref = ref or repository["ref"]
    if not isinstance(source_ref, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_./-]*", source_ref) or ".." in source_ref:
        raise ValueError("Invalid plugin source ref")
    if release and not re.fullmatch(r"[0-9a-f]{40,64}", source_ref):
        raise ValueError("Release catalogs require a full immutable commit ID via --ref")
    if not re.fullmatch(r"https://github\.com/[\w.-]+/[\w.-]+", repository["url"]):
        raise ValueError("Invalid plugin repository URL")
    catalog = {"_comment": "Generated by tooling/scripts/generate_registry.py from plugins/*/pyproject.toml."}
    identifiers = set()
    for path in sorted((root / "plugins").glob("*/pyproject.toml")):
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        project = data["project"]
        plugin = data["tool"]["pymss"]["plugin"]
        studio = data["tool"]["pymss"]["studio"]
        if plugin["id"] in identifiers:
            raise ValueError(f"Duplicate plugin ID: {plugin['id']}")
        identifiers.add(plugin["id"])
        if studio.get("category") not in {"convert", "analyze", "recognize", "edit"}:
            raise ValueError(f"Invalid plugin category: {path.parent.name}")
        if not isinstance(project.get("version"), str) or not project["version"].strip():
            raise ValueError(f"Missing plugin version: {path.parent.name}")
        locales = studio.get("locales", {})
        if not isinstance(locales, dict) or not all(isinstance(value, dict) for value in locales.values()):
            raise ValueError(f"Invalid plugin locales: {path.parent.name}")
        tags = studio.get("tags", [])
        if not isinstance(tags, list) or not all(isinstance(tag, str) for tag in tags):
            raise ValueError(f"Invalid plugin tags: {path.parent.name}")
        if plugin.get("api_version") != 2:
            raise ValueError(f"Plugin manifest must use api_version 2: {path.parent.name}")
        if release:
            validate_snapshot(path.parent, data)
        catalog[plugin["id"]] = {
            "id": plugin["id"], "api_version": plugin["api_version"],
            "url": repository["url"], "subpath": path.parent.relative_to(root).as_posix(),
            "ref": source_ref, "version": project["version"],
            "requires_pymss": plugin.get("requires_pymss"),
            "operations": [operation["id"] for operation in plugin.get("operations", [])],
            "description": locales.get("en", {}).get("description") or project.get("description", ""),
            "tags": tags, "category": studio["category"], "locales": locales,
            "requirements": studio_requirements(studio),
        }
    return catalog


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--ref", help="Plugin source commit; required for a release catalog")
    parser.add_argument("--release", action="store_true")
    args = parser.parse_args()
    catalog = render_registry(ref=args.ref, release=args.release)
    content = json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"
    target = ROOT / "registry.json"
    if args.check:
        if target.read_text(encoding="utf-8") != content:
            parser.exit(1, "Plugin catalog is stale; run python tooling/scripts/generate_registry.py\n")
    else:
        target.write_text(content, encoding="utf-8", newline="\n")
    print(f"{'Checked' if args.check else 'Generated'} {len(catalog) - 1} plugin catalog entries")


if __name__ == "__main__":
    main()
