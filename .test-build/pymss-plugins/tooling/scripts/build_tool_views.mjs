import { readFile, writeFile, mkdir, mkdtemp, rm, readdir } from 'node:fs/promises'
import path from 'node:path'
import os from 'node:os'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import { build } from 'vite'
import vue from '@vitejs/plugin-vue'
import Components from 'unplugin-vue-components/vite'
import { NaiveUiResolver } from 'unplugin-vue-components/resolvers'

const tooling = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const root = path.resolve(tooling, '..')
const frontend = path.join(tooling, 'frontend')
const entries = JSON.parse(execFileSync('python', ['-X', 'utf8', path.join(tooling, 'scripts/view_components.py')], { encoding: 'utf8' }))
const requested = process.argv.find(value => value.startsWith('--tool='))?.slice(7)
const check = process.argv.includes('--check')
if (requested && !entries.some(entry => entry.fileTool === requested || entry.plugin === requested)) throw new Error(`Unknown plugin component: ${requested}`)
const packageBuilds = new Set()

async function loadLocales(packageRoot) {
  const directory = path.join(packageRoot, 'ui/src/locales')
  const files = (await readdir(directory)).filter(file => file.endsWith('.json')).sort()
  const messages = Object.fromEntries(await Promise.all(files.map(async file => {
    const locale = path.basename(file, '.json')
    if (!/^[a-z]{2,3}(?:-[a-z0-9]{2,8})*$/i.test(locale)) throw new Error(`Invalid locale filename: ${file}`)
    const data = JSON.parse(await readFile(path.join(directory, file), 'utf8'))
    if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error(`Locale must contain a message object: ${file}`)
    return [locale, data]
  })))
  if (!messages.en) throw new Error(`Missing English fallback dictionary: ${directory}/en.json`)
  return messages
}

for (const entry of entries) {
  const tool = entry.fileTool || entry.plugin
  if (requested && requested !== tool && requested !== entry.plugin) continue
  if (entry.buildScript) {
    if (!packageBuilds.has(entry.buildScript)) {
      execFileSync(process.execPath, [entry.buildScript, ...(check ? ['--check'] : [])], { cwd: entry.packageRoot, stdio: 'inherit' })
      packageBuilds.add(entry.buildScript)
    }
    if (!(await readFile(entry.entry)).length) throw new Error(`Plugin page is empty: ${entry.plugin}`)
    continue
  }
  const messages = await loadLocales(entry.packageRoot)
  const temporary = await mkdtemp(path.join(os.tmpdir(), 'pymss-tool-build-'))
  try {
    await build({
      configFile: false, root: frontend, logLevel: 'error',
      plugins: [
        vue(), Components({ resolvers: [NaiveUiResolver()], dts: false }),
        {
          name: 'plugin-locales',
          resolveId(id) { if (id === '@tool/locales') return '\0plugin-locales' },
          load(id) { if (id === '\0plugin-locales') return `export default ${JSON.stringify(messages)}` },
        },
      ],
      define: {
        __FILE_TOOL__: JSON.stringify(tool), __OPERATION_ID__: JSON.stringify(entry.operation),
        __USE_FILE_TOOL_RUNTIME__: Boolean(entry.fileTool),
        __STUDIO_REQUIREMENTS__: JSON.stringify(entry.requirements),
        'process.env.NODE_ENV': JSON.stringify('production'),
        __VUE_OPTIONS_API__: true, __VUE_PROD_DEVTOOLS__: false, __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: false,
      },
      resolve: { dedupe: ['vue', 'vue-i18n', 'naive-ui', '@vicons/ionicons5'], alias: [
        { find: /^@tauri-apps\/(?:api\/(?:core|event)|plugin-shell)$/, replacement: path.join(frontend, 'src/sdk.ts') },
        { find: '@tool/entry', replacement: entry.component },
        { find: '@', replacement: path.join(frontend, 'src') },
      ] },
      build: { outDir: temporary, emptyOutDir: false, cssCodeSplit: false, sourcemap: false,
        license: { fileName: 'THIRD-PARTY-NOTICES.txt' },
        lib: { entry: path.join(frontend, 'src/main.ts'), name: 'PymssTool', formats: ['iife'], fileName: () => 'tool.js', cssFileName: 'tool' },
        rollupOptions: { output: { inlineDynamicImports: true } },
      },
    })
    const files = await readdir(temporary)
    const js = await readFile(path.join(temporary, 'tool.js'), 'utf8')
    const css = (await Promise.all(files.filter(file => file.endsWith('.css')).map(file => readFile(path.join(temporary, file), 'utf8')))).join('\n')
    const html = `<!doctype html>\n<!-- Generated by tooling/scripts/build_tool_views.mjs. -->\n<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style></head><body><div id="app"></div><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>\n`
    const target = entry.entry
    const notice = await readFile(path.join(temporary, 'THIRD-PARTY-NOTICES.txt'), 'utf8')
    const noticeTarget = path.join(root, `plugins/${entry.plugin}/THIRD-PARTY-NOTICES.txt`)
    if (check) {
      if (await readFile(target, 'utf8') !== html) throw new Error(`Outdated tool page: ${entry.plugin}`)
      if (await readFile(noticeTarget, 'utf8') !== notice) throw new Error(`Outdated tool notices: ${entry.plugin}`)
    } else {
      await mkdir(path.dirname(target), { recursive: true })
      await writeFile(target, html)
      await writeFile(noticeTarget, notice)
    }
    process.stdout.write(`${check ? 'Checked' : 'Built'} ${tool}: ${Math.round(Buffer.byteLength(html) / 1024)} KiB\n`)
  } finally { await rm(temporary, { recursive: true, force: true }) }
}
